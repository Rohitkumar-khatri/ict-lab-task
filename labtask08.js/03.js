function add(a, b) {
  return a + b;
}

function square(n) {
  return n * n;
}

function greet(name) {
  return "Hello, " + name;
}

function areaOfRectangle(length, width) {
  return length * width;
}

console.log(add(2, 3));
console.log(add(10, 15));

console.log(square(4));
console.log(square(7));

console.log(greet("Govind"));
console.log(greet("Ali"));

console.log(areaOfRectangle(5, 3));
console.log(areaOfRectangle(10, 4));
